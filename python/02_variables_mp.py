# Declaracion de variables

nombre_producto = "Martillo de acero"
stock = 25
print(nombre_producto)
print(stock)

proveedor: str = "Distribuidora Andina"
print(proveedor)

print("Tipos de Variables")
print("Tipo Texto o String .str")
categoria = "Herramientas"
print(categoria)
print(type(categoria))

print("Tipo de variable Entera .int")
stock_minimo = 5
print(stock_minimo)
print(type(stock_minimo))

print("Tipo de variable float .decimal")
precio_unitario = 8.50
print(precio_unitario)
print(type(precio_unitario))

print("Tipo de variable boolean .bool")
producto_disponible = True
print(producto_disponible)
print(type(producto_disponible))

print("Movimientos de stock")
cajas = 10
print(cajas)
cajas = 10 + 5
print(cajas)
cajas += 5
print(cajas)
cajas -= 8
print(cajas)
